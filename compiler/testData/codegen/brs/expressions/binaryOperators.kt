// Binary operators test
fun arithmeticOps(a: Int, b: Int) {
    val sum = a + b
    val diff = a - b
    val product = a * b
    val quotient = a / b
    val remainder = a % b
}

fun comparisonOps(a: Int, b: Int) {
    val lt = a < b
    val gt = a > b
    val le = a <= b
    val ge = a >= b
    val eq = a == b
    val ne = a != b
}

fun logicalOps(a: Boolean, b: Boolean) {
    val and = a && b
    val or = a || b
    val not = !a
}
